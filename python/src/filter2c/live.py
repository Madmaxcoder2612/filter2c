"""A live check of the filter on a real board, with a real analog input.

The self-test in ``target.py`` feeds the filter a stored signal. This check goes
one step further and uses the board's own analog-to-digital converter:

1. ``create_live_sketch`` writes a sketch. The board drives one of its pins as a
   slow square wave, reads it back through its analog input (the user connects
   the two pins with one jumper wire), takes readings at the filter's sampling
   rate, runs the filter, and only afterwards prints time, raw reading and
   filtered value. Printing after the measurement keeps it from disturbing the
   timing.
2. ``check_live_log`` reads that output on the PC and checks three things: the
   board really sampled at the expected rate, the input really changed, and the
   filter output equals SciPy's filter applied to the same raw readings.

The sketch uses only ``micros``, ``millis``, ``analogRead``, ``digitalWrite`` and
``Serial.print``, which every Arduino board has.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from string import Template

import numpy as np
from scipy import signal

from . import __version__
from .codegen import check_name, generate_header, runtime_header
from .design import FilterDesign
from .target import META_FILE, _RESERVED_NAMES, _SKETCH_FOLDER, _design_from_meta, _design_parameters
from .verify import DEFAULT_TOLERANCE, VerificationError

LIVE_SAMPLES = 2000
DEFAULT_MAX_PERIOD_ERROR = 0.005  # mean sample period may be off by 0.5 %
DEFAULT_MIN_SWING = 1000.0        # the raw reading must move by at least this many counts

_LIVE_RESERVED = _RESERVED_NAMES | {
    "timeUs", "raw", "filtered", "acquire", "micros", "analogRead", "digitalWrite", "pinMode",
}

_LIVE_SKETCH = Template(
    """/*
 * Generated by filter2c ${version}: live check of the filter "${name}" on a real board.
 *
 * The board drives one of its own pins as a slow square wave (5 Hz) and reads it
 * back with its analog input. Connect the two pins with ONE jumper wire, nothing
 * else is needed:
 *     output pin OUT_PIN  --- wire ---  analog input pin ADC_PIN
 * The pin numbers below are for ESP32-S3 boards (GPIO2 and GPIO1). On other
 * boards change them.
 *
 * The sketch takes ${samples} readings at exactly ${fs} Hz and runs the filter on
 * each one. Only afterwards it prints time, raw reading and filtered value, so
 * the printing cannot disturb the timing. The block repeats every 5 seconds.
 *
 * What to do:
 *   1. Connect the two pins with the jumper wire, select your board and upload.
 *   2. Open the Serial Monitor at 921600 baud (ignored on a native USB port).
 *   3. Wait for FILTER2C_LIVE_END, select all the text and save it as live.txt.
 *   4. On the PC run:  filter2c check-live-log <this folder> live.txt
 */
#include <Arduino.h>

#include "filter2c.h"
#include "${name}.h"

#if defined(ARDUINO_ARCH_ESP32)
const int OUT_PIN = 2;   // GPIO2
const int ADC_PIN = 1;   // GPIO1
#else
const int OUT_PIN = 2;   // D2
const int ADC_PIN = A0;
#endif

const unsigned int SAMPLES = ${samples}u;
const unsigned long PERIOD_US = ${period_us}ul;  // ${fs} Hz, must match the filter design
const unsigned long HALF_CYCLE_MS = 100;         // 100 ms high, 100 ms low: a 5 Hz square wave

static uint32_t timeUs[SAMPLES];
static uint16_t raw[SAMPLES];
static float filtered[SAMPLES];

static void acquire(void)
{
    unsigned int i;
    unsigned long next;
    filter2c_reset(&${name});
    next = micros();
    for (i = 0; i < SAMPLES; ++i) {
        // Wait for the next sample time. The subtraction also works when micros() wraps around.
        while ((long)(micros() - next) < 0) {
        }
        next += PERIOD_US;
        digitalWrite(OUT_PIN, ((millis() / HALF_CYCLE_MS) & 1) ? HIGH : LOW);
        timeUs[i] = (uint32_t)micros();
        raw[i] = (uint16_t)analogRead(ADC_PIN);
        filtered[i] = filter2c_process(&${name}, (float)raw[i]);
    }
}

void setup()
{
    unsigned long start = millis();
    pinMode(OUT_PIN, OUTPUT);
    Serial.begin(921600);
    while (!Serial && millis() - start < 5000) {
        // Wait for the USB serial connection, but not forever.
    }
    delay(1000);
}

void loop()
{
    unsigned int i;

    acquire();

    Serial.println("FILTER2C_LIVE_BEGIN");
    for (i = 0; i < SAMPLES; ++i) {
        Serial.print(timeUs[i]);
        Serial.print(',');
        Serial.print(raw[i]);
        Serial.print(',');
        Serial.println(filtered[i], 5);
    }
    Serial.println("FILTER2C_LIVE_END");
    Serial.print("FILTER2C_LIVE_SAMPLES=");
    Serial.println(SAMPLES);

    delay(5000);
}
"""
)


def create_live_sketch(
    design: FilterDesign, name: str, folder: Path, samples: int = LIVE_SAMPLES
) -> list[Path]:
    """Write a ready-to-upload live-check sketch folder and return the files created."""
    check_name(name)
    if name in _LIVE_RESERVED:
        raise ValueError(f"the filter name {name!r} clashes with a name used in the sketch")
    if not _SKETCH_FOLDER.match(folder.name):
        raise ValueError(
            f"{folder.name!r} is not a usable sketch folder name "
            "(letters, digits, underscores and dashes only)"
        )
    period_us = round(1e6 / design.fs_hz)
    if period_us < 1 or abs(period_us * design.fs_hz - 1e6) > 1e-6 * 1e6:
        raise ValueError(
            f"a sampling rate of {design.fs_hz:g} Hz does not give a whole number of "
            "microseconds per sample; use a rate such as 100, 250, 500 or 1000 Hz"
        )
    if samples < 100:
        raise ValueError("a live check needs at least 100 samples")

    meta = {
        **_design_parameters(design),
        "fs_hz": design.fs_hz,
        "name": name,
        "samples": samples,
        "mode": "live",
        "filter2c_version": __version__,
    }
    contents = {
        f"{folder.name}.ino": _LIVE_SKETCH.substitute(
            version=__version__, name=name, samples=samples, period_us=period_us,
            fs=f"{design.fs_hz:g}",
        ),
        f"{name}.h": generate_header(design, name),
        "filter2c.h": runtime_header(),
        META_FILE: json.dumps(meta, indent=2) + "\n",
    }
    folder.mkdir(parents=True, exist_ok=True)
    written = []
    for filename, text in contents.items():
        path = folder / filename
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


_LIVE_BLOCK = re.compile(r"FILTER2C_LIVE_BEGIN(.*?)FILTER2C_LIVE_END", re.DOTALL)


def parse_live_log(text: str, expected_samples: int) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Read the last complete block: time in microseconds, raw reading, filtered value.

    Serial monitors may add a timestamp and ``->`` in front of each line; only
    what comes after the last ``->`` is read.
    """
    blocks = _LIVE_BLOCK.findall(text)
    if not blocks:
        raise VerificationError(
            "no complete result found in the log (needs FILTER2C_LIVE_BEGIN and FILTER2C_LIVE_END). "
            "Wait for the block to finish printing, then copy again."
        )
    times, raws, outs = [], [], []
    for line in blocks[-1].splitlines():
        line = line.split("->")[-1].strip()
        if not line:
            continue
        fields = line.split(",")
        try:
            if len(fields) != 3:
                raise ValueError
            times.append(int(fields[0]))
            raws.append(int(fields[1]))
            outs.append(float(fields[2]))
        except ValueError as error:
            raise VerificationError(f"unreadable line in the log: {line!r}") from error
    if len(times) != expected_samples:
        raise VerificationError(
            f"the log has {len(times)} samples, expected {expected_samples}. "
            "Copy the whole block, from FILTER2C_LIVE_BEGIN to FILTER2C_LIVE_END."
        )
    return (
        np.array(times, dtype=np.int64),
        np.array(raws, dtype=np.float64),
        np.array(outs, dtype=np.float64),
    )


@dataclass(frozen=True)
class LiveReport:
    samples: int
    expected_period_us: float
    mean_period_us: float
    min_period_us: float
    max_period_us: float
    std_period_us: float
    late_fraction: float  # share of sample intervals longer than 1.5 x the expected period
    raw_min: float
    raw_max: float
    max_abs_error: float
    relative_error: float
    tolerance: float
    timing_ok: bool
    signal_ok: bool
    accuracy_ok: bool

    @property
    def passed(self) -> bool:
        return self.timing_ok and self.signal_ok and self.accuracy_ok


def check_live_log(
    folder: Path,
    log_text: str,
    tolerance: float = DEFAULT_TOLERANCE,
    max_period_error: float = DEFAULT_MAX_PERIOD_ERROR,
    min_swing: float = DEFAULT_MIN_SWING,
) -> LiveReport:
    """Check a live log against the design in the sketch folder."""
    meta_path = folder / META_FILE
    if not meta_path.exists():
        raise VerificationError(f"{meta_path} not found: is this a folder made by target-sketch?")
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    if meta.get("mode") != "live":
        raise VerificationError(
            "this folder holds a self-test sketch, not a live-check sketch. "
            "Use check-board-log, or make a live sketch with: target-sketch <filter> --live"
        )
    design = _design_from_meta(meta)
    samples = int(meta["samples"])

    times, raw, filtered = parse_live_log(log_text, samples)

    expected = 1e6 / design.fs_hz
    periods = np.diff(times) % (2 ** 32)  # micros() wraps around after about 71 minutes
    mean_period = float(np.mean(periods))
    swing = float(raw.max() - raw.min())

    reference = signal.sosfilt(design.sos, raw)
    max_abs = float(np.max(np.abs(filtered - reference)))
    peak = float(np.max(np.abs(reference)))
    relative = max_abs / peak if peak > 0 else float("inf")

    return LiveReport(
        samples=samples,
        expected_period_us=expected,
        mean_period_us=mean_period,
        min_period_us=float(periods.min()),
        max_period_us=float(periods.max()),
        std_period_us=float(np.std(periods)),
        late_fraction=float(np.mean(periods > 1.5 * expected)),
        raw_min=float(raw.min()),
        raw_max=float(raw.max()),
        max_abs_error=max_abs,
        relative_error=relative,
        tolerance=tolerance,
        timing_ok=bool(abs(mean_period - expected) / expected <= max_period_error),
        signal_ok=bool(swing >= min_swing),
        accuracy_ok=bool(relative <= tolerance),
    )
