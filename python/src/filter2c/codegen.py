"""Turn a FilterDesign into a C header."""
from __future__ import annotations

import re
from importlib import resources

import numpy as np

from . import __version__
from .design import FilterDesign

_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

# Reserved words of C99 and C++, so the generated names compile in both.
_RESERVED = frozenset(
    """auto break case char const continue default do double else enum extern
    float for goto if inline int long register restrict return short signed
    sizeof static struct switch typedef union unsigned void volatile while
    bool class namespace new delete template this try catch throw true false
    public private protected virtual operator friend using""".split()
)


def check_name(name: str) -> str:
    """Return ``name`` if it can be used as a C identifier, else raise ValueError."""
    if not _IDENTIFIER.match(name) or name in _RESERVED:
        raise ValueError(
            f"{name!r} is not a usable C identifier "
            "(letters, digits and underscores, not starting with a digit, not a keyword)"
        )
    return name


def float32_literal(value: float) -> str:
    """Write a value as a C float literal that reads back as the same float32."""
    with np.errstate(over="ignore"):
        as_f32 = np.float32(value)
    if not np.isfinite(as_f32):
        raise ValueError(f"coefficient {value!r} does not fit in a float")
    # 9 significant digits are enough to identify any float32 exactly.
    text = f"{float(as_f32):.9g}"
    if not any(c in text for c in ".eE"):
        text += ".0"
    return text + "f"


def runtime_header() -> str:
    """Return the text of filter2c.h that ships inside this package."""
    return (resources.files("filter2c") / "runtime" / "filter2c.h").read_text(encoding="utf-8")


def generate_header(design: FilterDesign, name: str) -> str:
    """Generate the C header for a design.

    The header includes ``filter2c.h`` and defines a ready-to-use filter called
    ``name``. It is meant to be included from one source file.
    """
    check_name(name)
    upper = name.upper()
    count = design.sections
    rows = []
    for b0, b1, b2, a0, a1, a2 in design.sos:
        if a0 != 1.0:
            raise ValueError("expected sections normalised to a0 == 1")
        coefficients = ", ".join(float32_literal(v) for v in (b0, b1, b2, a1, a2))
        rows.append(f"    {{ {coefficients} }}")
    table = ",\n".join(rows)

    return f"""/* Generated by filter2c {__version__}. Do not edit by hand.
 *
 * {design.describe()}
 * {count} biquad section(s), Direct Form II Transposed, float (32 bit).
 *
 * Usage:
 *     #include "{name}.h"
 *     filter2c_reset(&{name});
 *     float y = filter2c_process(&{name}, x);
 *
 * Include this header from one source file only.
 */
#ifndef FILTER2C_GENERATED_{upper}_H
#define FILTER2C_GENERATED_{upper}_H

#include "filter2c.h"

#define {upper}_SECTIONS {count}u

static const filter2c_section {name}_sections[{upper}_SECTIONS] = {{
{table}
}};

static float {name}_state[2u * {upper}_SECTIONS];

static const filter2c_sos {name} = {{ {name}_sections, {name}_state, {upper}_SECTIONS }};

#endif /* FILTER2C_GENERATED_{upper}_H */
"""
