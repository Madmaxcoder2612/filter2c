"""Run the generated filter on a real board and check what the board says.

Workflow:

1. ``create_sketch`` writes an Arduino sketch folder. The sketch runs the filter
   on a built-in test signal, times it, and prints the result over serial.
2. The user uploads it, copies the serial output into a text file.
3. ``check_board_log`` compares the board's numbers with SciPy and with the same
   C code compiled on the PC, and reports the speed.

The sketch uses ``ESP.getCycleCount()`` and ``getCpuFrequencyMhz()``, so it is
written for ESP32 boards.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from string import Template

import numpy as np
from scipy import signal

from . import __version__
from .codegen import check_name, float32_literal, generate_header, runtime_header
from .design import FilterDesign, butterworth_lowpass
from .verify import (
    DEFAULT_TOLERANCE,
    VerificationError,
    find_compiler,
    make_test_signal,
    run_c_filter,
)

SAMPLES = 1024
META_FILE = "filter2c_target.json"

# Names that would clash with files or identifiers used inside the sketch.
_RESERVED_NAMES = frozenset(
    {"filter2c", "testsignal", "setup", "loop", "main", "Serial", "ESP", "delay", "millis"}
)
_SKETCH_FOLDER = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_-]{0,62}$")

_SKETCH = Template(
    """/*
 * Generated by filter2c ${version}: on-board self-test for ESP32 boards.
 *
 * The sketch runs the filter "${name}" on a built-in test signal, measures the
 * time per sample and prints the result over the serial port at 115200 baud.
 * The block of numbers repeats every 10 seconds.
 *
 * What to do:
 *   1. Select your ESP32 board and upload this sketch.
 *   2. Open the Serial Monitor at 115200 baud and wait until FILTER2C_END appears.
 *   3. Select all the text, copy it and save it as board.txt.
 *   4. On the PC run:  filter2c check-board-log <this folder> board.txt
 *
 * No output on an ESP32-S3 when using its USB port? In the Arduino IDE set
 * Tools > USB CDC On Boot > Enabled, then upload again.
 */
#include <Arduino.h>

#include "filter2c.h"
#include "${name}.h"
#include "testsignal.h"

static float f2c_output[F2C_TEST_SAMPLES];

static void f2c_run(void)
{
    unsigned int i;
    filter2c_reset(&${name});
    for (i = 0; i < F2C_TEST_SAMPLES; ++i) {
        f2c_output[i] = filter2c_process(&${name}, f2c_test_input[i]);
    }
}

void setup()
{
    unsigned long start = millis();
    Serial.begin(115200);
    while (!Serial && millis() - start < 5000) {
        // Wait for the USB serial connection, but not forever.
    }
    delay(1000);
}

void loop()
{
    unsigned int i;
    uint32_t t0, cycles;

    f2c_run();  // first pass warms up the instruction and data caches
    t0 = ESP.getCycleCount();
    f2c_run();  // second pass is timed
    cycles = ESP.getCycleCount() - t0;

    Serial.println("FILTER2C_BEGIN");
    for (i = 0; i < F2C_TEST_SAMPLES; ++i) {
        Serial.printf("%.9g\\n", (double)f2c_output[i]);
    }
    Serial.println("FILTER2C_END");
    Serial.printf("FILTER2C_SAMPLES=%u\\n", (unsigned int)F2C_TEST_SAMPLES);
    Serial.printf("FILTER2C_CPU_MHZ=%u\\n", (unsigned int)getCpuFrequencyMhz());
    Serial.printf("FILTER2C_CYCLES_PER_SAMPLE=%.2f\\n", (double)cycles / (double)F2C_TEST_SAMPLES);

    delay(10000);
}
"""
)


def test_signal_header(x: np.ndarray) -> str:
    """C header holding the test signal as a float array."""
    values = [float32_literal(v) for v in x]
    lines = []
    for start in range(0, len(values), 8):
        lines.append("    " + ", ".join(values[start:start + 8]))
    body = ",\n".join(lines)
    return f"""/* Generated by filter2c {__version__}. Test signal for the on-board self-test. */
#ifndef FILTER2C_GENERATED_TESTSIGNAL_H
#define FILTER2C_GENERATED_TESTSIGNAL_H

#define F2C_TEST_SAMPLES {len(values)}u

static const float f2c_test_input[F2C_TEST_SAMPLES] = {{
{body}
}};

#endif /* FILTER2C_GENERATED_TESTSIGNAL_H */
"""


def create_sketch(
    design: FilterDesign, name: str, folder: Path, samples: int = SAMPLES
) -> list[Path]:
    """Write a ready-to-upload sketch folder and return the files created."""
    check_name(name)
    if name in _RESERVED_NAMES:
        raise ValueError(f"the filter name {name!r} clashes with a name used in the sketch")
    if not _SKETCH_FOLDER.match(folder.name):
        raise ValueError(
            f"{folder.name!r} is not a usable sketch folder name "
            "(letters, digits, underscores and dashes only)"
        )
    x = make_test_signal(design.fs_hz, samples)
    meta = {
        "filter": "butterworth-lowpass",
        "order": design.order,
        "cutoff_hz": design.cutoff_hz,
        "fs_hz": design.fs_hz,
        "name": name,
        "samples": samples,
        "filter2c_version": __version__,
    }
    contents = {
        f"{folder.name}.ino": _SKETCH.substitute(version=__version__, name=name),
        f"{name}.h": generate_header(design, name),
        "testsignal.h": test_signal_header(x),
        "filter2c.h": runtime_header(),
        META_FILE: json.dumps(meta, indent=2) + "\n",
    }
    folder.mkdir(parents=True, exist_ok=True)
    written = []
    for filename, text in contents.items():
        path = folder / filename
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


@dataclass(frozen=True)
class BoardLog:
    outputs: np.ndarray
    cpu_mhz: float
    cycles_per_sample: float


@dataclass(frozen=True)
class TargetReport:
    samples: int
    max_abs_error: float
    relative_error: float
    tolerance: float
    passed: bool
    identical_to_pc_build: bool | None  # None if no C compiler was available
    max_diff_to_pc_build: float | None
    cpu_mhz: float
    cycles_per_sample: float

    @property
    def microseconds_per_sample(self) -> float:
        return self.cycles_per_sample / self.cpu_mhz

    @property
    def max_sample_rate_hz(self) -> float:
        return 1e6 / self.microseconds_per_sample


_BLOCK = re.compile(r"FILTER2C_BEGIN(.*?)FILTER2C_END(.*?)(?=FILTER2C_BEGIN|\Z)", re.DOTALL)


def parse_board_log(text: str, expected_samples: int) -> BoardLog:
    """Read the last complete block of serial output.

    Serial monitors may add timestamps before each line, so only the last
    word of each line is read.
    """
    blocks = [m for m in _BLOCK.finditer(text) if "FILTER2C_CYCLES_PER_SAMPLE=" in m.group(2)]
    if not blocks:
        raise VerificationError(
            "no complete result found in the log (needs FILTER2C_BEGIN, FILTER2C_END and the "
            "FILTER2C_ lines after it). Wait for the block to finish printing, then copy again."
        )
    block = blocks[-1]
    numbers = []
    for line in block.group(1).splitlines():
        words = line.split()
        # A timestamp prefix ("12:00:01.123 ->") can be left over in front of a marker.
        if not words or words[-1] == "->":
            continue
        try:
            numbers.append(float(words[-1]))
        except ValueError as error:
            raise VerificationError(f"unreadable line in the log: {line!r}") from error
    if len(numbers) != expected_samples:
        raise VerificationError(
            f"the log has {len(numbers)} samples, expected {expected_samples}. "
            "Copy the whole block, from FILTER2C_BEGIN to the last FILTER2C_ line."
        )

    def stat(key: str) -> float:
        match = re.search(rf"{key}=([0-9.eE+-]+)", block.group(2))
        if not match:
            raise VerificationError(f"{key} is missing from the log")
        return float(match.group(1))

    cpu = stat("FILTER2C_CPU_MHZ")
    cycles = stat("FILTER2C_CYCLES_PER_SAMPLE")
    if cpu <= 0 or cycles <= 0:
        raise VerificationError("the clock speed and cycle count in the log must be positive")
    return BoardLog(np.array(numbers, dtype=np.float64), cpu, cycles)


def read_test_signal(folder: Path) -> np.ndarray:
    """Read the test signal back from the sketch folder, exactly as the board sees it."""
    text = (folder / "testsignal.h").read_text(encoding="utf-8")
    match = re.search(r"=\s*\{(.*?)\}\s*;", text, re.DOTALL)
    if not match:
        raise VerificationError("could not read the test signal from testsignal.h")
    values = re.findall(r"[-+]?\d[\d.]*(?:[eE][-+]?\d+)?(?=f)", match.group(1))
    return np.array([np.float32(v) for v in values], dtype=np.float32)


def check_board_log(
    folder: Path, log_text: str, tolerance: float = DEFAULT_TOLERANCE
) -> TargetReport:
    """Compare what the board printed with SciPy and with the PC build."""
    meta_path = folder / META_FILE
    if not meta_path.exists():
        raise VerificationError(f"{meta_path} not found: is this a folder made by target-sketch?")
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    design = butterworth_lowpass(meta["order"], meta["cutoff_hz"], meta["fs_hz"])
    name, samples = meta["name"], int(meta["samples"])

    x = read_test_signal(folder)
    if x.size != samples:
        raise VerificationError(f"testsignal.h has {x.size} samples, expected {samples}")
    board = parse_board_log(log_text, samples)

    reference = signal.sosfilt(design.sos, x.astype(np.float64))
    max_abs = float(np.max(np.abs(board.outputs - reference)))
    relative = max_abs / float(np.max(np.abs(reference)))

    identical = diff = None
    if find_compiler() is not None:
        pc = run_c_filter(generate_header(design, name), runtime_header(), name, x)
        diff = float(np.max(np.abs(board.outputs - pc)))
        identical = bool(np.array_equal(board.outputs.astype(np.float32), pc.astype(np.float32)))

    return TargetReport(
        samples=samples,
        max_abs_error=max_abs,
        relative_error=relative,
        tolerance=tolerance,
        passed=bool(relative <= tolerance),
        identical_to_pc_build=identical,
        max_diff_to_pc_build=diff,
        cpu_mhz=board.cpu_mhz,
        cycles_per_sample=board.cycles_per_sample,
    )
